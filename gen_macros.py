#!/usr/bin/env python3
"""Generate LaTeX macros from saved result JSONs. The EP, Cluster and FTT macro block contains manually entered historical values and needs separate verification. This script does not rerun experiments."""
import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"
OUT = Path(__file__).resolve().parent / "macros.tex"


def load(name):
    with open(RESULTS / name) as f:
        return json.load(f)


def f3(x):
    """3-decimal fixed, LaTeX-safe."""
    return f"{x:.3f}"


def pct2(x):
    return f"{x*100:.2f}\\%"


def commanum(n):
    return f"{int(round(n)):,}".replace(",", "{,}")


# ── load ────────────────────────────────────────────────────────────
bi = load("baselines_ieee_cis.json")
bt = load("baselines_tabformer.json")
ai = load("ablations_ieee_cis.json")["results"]
at = load("ablations_tabformer.json")["results"]
ci = load("catboost_ieee_cis.json")
ct = load("catboost_tabformer.json")


def base_row(b, key):
    v = b["full_label"][key]
    return v["linear"]["auprc"], v["gbdt"]["auprc"], v["gbdt"]["auc"]


def le(b, key, frac):
    return b["label_efficiency"][key][frac]["auprc"]


# label-efficiency fractions -> macro-name fragment (100% == full linear AUPRC, emitted separately)
LE_FRACS = [("onepc", "0.01"), ("fivepc", "0.05"), ("tenpc", "0.10"), ("twentyfivepc", "0.25")]
LE_METHODS = [("raw", "raw"), ("pca", "pca16"), ("freq", "freq"), ("gater", "gater16")]


def abl_lin_gbdt(res, key):
    v = res[key]["full_label"]
    return v["linear"]["auprc"], v["gbdt"]["auprc"]


def cat(c):
    v = c["full_label"]["catboost"]["gbdt"]
    return v["auprc"], v["auc"], c["label_efficiency"]["catboost"]["0.01"]["auprc"]


# ── figure/entity/FTT macros NOT in the six JSONs ────────────────────
# These come from separate runs (UMAP/entity profiling on gater_*.npy; FT-Transformer
# supervised-ceiling run). REFRESH the EP*/Cluster* block when the C2 figures regenerate.
MANUAL = r"""
% ── Cluster stability (K-means on IEEE-CIS C2 latent, k=3, 10 runs) ──────────
\newcommand{\ClusterARI}{0.9991}
\newcommand{\ClusterARIstd}{0.0005}

% ── Entity profiling (K-means on IEEE-CIS C2 latent, k=3) ────────────────────
\newcommand{\EPkbest}{3}
\newcommand{\EPsil}{0.085}
\newcommand{\EPConefraud}{8.4\%}
\newcommand{\EPCtwofraud}{3.0\%}
\newcommand{\EPCthreefraud}{2.1\%}
\newcommand{\EPConesize}{103K}
\newcommand{\EPoverall}{3.5\%}
\newcommand{\EPfraudratio}{4.0$\times$}

% ── FT-Transformer supervised ceiling (IEEE-CIS, 3 seeds) – separate run ────
\newcommand{\FTTonepc}{0.253}
\newcommand{\FTTonepcStd}{0.022}
\newcommand{\FTTtenpc}{0.459}
\newcommand{\FTTtwentyfivepc}{0.558}
\newcommand{\FTTfull}{0.696}
\newcommand{\FTTfullStd}{0.002}
\newcommand{\FTToneGap}{4.7}
"""


def main():
    L = []
    w = L.append
    w("% Auto-generated by gen_macros.py from results/*.json – do NOT hand-edit.")
    w("% Re-run: python gen_macros.py  (after any results JSON changes)")
    w("% Source: baselines_{ieee_cis,tabformer}.json, ablations_{...}.json, catboost_{...}.json")
    w("")

    # IEEE baselines
    w("% ── IEEE-CIS baselines ──────────────────────────────────────────────")
    w(f"\\newcommand{{\\IEEErows}}{{{commanum(bi['n_rows'])}}}")
    w(f"\\newcommand{{\\IEEEfraud}}{{{pct2(bi['fraud_rate'])}}}")
    for key, tag in (("raw", "raw"), ("pca16", "pca"), ("gater16", "gater")):
        lin, gbdt, auc = base_row(bi, key)
        w(f"% {key}")
        w(f"\\newcommand{{\\IEEE{tag}LinAUPRC}}{{{f3(lin)}}}")
        w(f"\\newcommand{{\\IEEE{tag}GBDTAUPRC}}{{{f3(gbdt)}}}")
        w(f"\\newcommand{{\\IEEE{tag}GBDTAUC}}{{{f3(auc)}}}")
    w("% label-efficiency grid (linear probe): {tag}LE{onepc,fivepc,tenpc,twentyfivepc}; 100% == LinAUPRC")
    for tag, key in LE_METHODS:
        if key not in bi["label_efficiency"]:
            continue
        for frac_name, frac in LE_FRACS:
            w(f"\\newcommand{{\\IEEE{tag}LE{frac_name}}}{{{f3(le(bi,key,frac))}}}")
    w("% full-label linear-probe seed std (5 seeds) for the headline comparison")
    w(f"\\newcommand{{\\IEEErawLinStd}}{{{f3(bi['full_label']['raw']['linear']['auprc_std'])}}}")
    w(f"\\newcommand{{\\IEEEgaterLinStd}}{{{f3(bi['full_label']['gater16']['linear']['auprc_std'])}}}")
    w("")

    # TabFormer baselines
    w("% ── TabFormer baselines ─────────────────────────────────────────────")
    w(f"\\newcommand{{\\TFrows}}{{{commanum(bt['n_rows'])}}}")
    w(f"\\newcommand{{\\TFfraud}}{{{pct2(bt['fraud_rate'])}}}")
    for key, tag in (("raw", "raw"), ("pca16", "pca"), ("freq", "freq"), ("gater16", "gater")):
        if key not in bt["full_label"]:
            continue
        lin, gbdt, auc = base_row(bt, key)
        w(f"% {key}")
        w(f"\\newcommand{{\\TF{tag}LinAUPRC}}{{{f3(lin)}}}")
        w(f"\\newcommand{{\\TF{tag}GBDTAUPRC}}{{{f3(gbdt)}}}")
        w(f"\\newcommand{{\\TF{tag}GBDTAUC}}{{{f3(auc)}}}")
    w("% label-efficiency grid (linear probe)")
    for tag, key in LE_METHODS:
        if key not in bt["label_efficiency"]:
            continue
        for frac_name, frac in LE_FRACS:
            w(f"\\newcommand{{\\TF{tag}LE{frac_name}}}{{{f3(le(bt,key,frac))}}}")
    _, tf_gater_gbdt, _ = base_row(bt, "gater16")
    _, tf_raw_gbdt, _ = base_row(bt, "raw")
    lift = round(tf_gater_gbdt / tf_raw_gbdt)
    w(f"\\newcommand{{\\TFgaterGBDTlift}}{{{lift}$\\times$}} % {f3(tf_gater_gbdt)} / {f3(tf_raw_gbdt)}")
    w("\\newcommand{\\TFfreqnote}{$\\ddagger$}")
    w("")

    # ablations: key -> macro tag
    ABL = [("full", "FULL"), ("no_contrastive", "NOCONT"), ("no_excision", "NOEXC"),
           ("excision_feature", "FEAT"), ("gru_encoder", "GRU"), ("mlp_encoder", "MLP"),
           ("scarf_augment", "SCARF"), ("no_kl_anneal", "NOKL"), ("z32", "ZTHIRTYTWO")]

    w("% ── IEEE-CIS ablations (5 seeds, 300 epochs, batch 16384) ──────────────────")
    for key, tag in ABL:
        if key not in ai:
            continue
        lin, gbdt = abl_lin_gbdt(ai, key)
        w(f"\\newcommand{{\\IEEEabl{tag}lin}}{{{f3(lin)}}}")
        w(f"\\newcommand{{\\IEEEabl{tag}gbdt}}{{{f3(gbdt)}}}")
    # within-ablation label-efficiency at 1% (for the KL-annealing comparison – same run)
    if "no_kl_anneal" in ai and "label_efficiency" in ai["no_kl_anneal"]:
        w(f"\\newcommand{{\\IEEEablNOKLLEonepc}}{{{f3(ai['no_kl_anneal']['label_efficiency']['0.01']['auprc'])}}}")
    if "full" in ai and "label_efficiency" in ai["full"]:
        w(f"\\newcommand{{\\IEEEablFULLLEonepc}}{{{f3(ai['full']['label_efficiency']['0.01']['auprc'])}}}")
    w("")

    w("% ── TabFormer ablations (5 seeds, 300 epochs) ──────────────────────────────")
    for key, tag in ABL:
        if key not in at:
            continue
        lin, gbdt = abl_lin_gbdt(at, key)
        w(f"\\newcommand{{\\TFabl{tag}lin}}{{{f3(lin)}}}")
        w(f"\\newcommand{{\\TFabl{tag}gbdt}}{{{f3(gbdt)}}}")
    w("")

    # CatBoost supervised skyline
    w("% ── CatBoost supervised skyline (5 seeds, native categoricals) ─────────────")
    ig, iauc, ile = cat(ci)
    tg, tauc, tle = cat(ct)
    w(f"\\newcommand{{\\IEEEcatboostGBDTAUPRC}}{{{f3(ig)}}}")
    w(f"\\newcommand{{\\IEEEcatboostGBDTAUC}}{{{f3(iauc)}}}")
    w(f"\\newcommand{{\\IEEEcatboostLEonepc}}{{{f3(ile)}}}")
    w(f"\\newcommand{{\\TFcatboostGBDTAUPRC}}{{{f3(tg)}}}")
    w(f"\\newcommand{{\\TFcatboostGBDTAUC}}{{{f3(tauc)}}}")
    w(f"\\newcommand{{\\TFcatboostLEonepc}}{{{f3(tle)}}}")

    # ── unsupervised representation comparison ────────────────────────────────
    # results/representation_comparison_ieee_cis.json -- all methods 16-dim,
    # label-free, scored with the SAME probe + K-means silhouette + train wall-time.
    # Representations are single-training-seed (one timed run); the 5-seed linear
    # probe supplies the AUPRC std. Robust claims: (a) CARTA+SCARF top quality tier
    # ~1.9x PCA (non-linear structure); (b) CARTA matches SCARF quality at a
    # fraction of its compute. Fine-grained excision-vs-SCARF quality is the
    # controlled 5-seed ablation (Table 3), not this coarse family-level scan.
    rc = load("representation_comparison_ieee_cis.json")["methods"]
    RC_TAGS = [("pca16", "PCA"), ("umap16", "UMAP"), ("ae", "AE"), ("sae", "SAE"),
               ("vanilla_vae", "VVAE"), ("scarf", "SCARF"), ("gater", "CARTA")]
    w("")
    w("% ── Unsupervised representation comparison (IEEE-CIS; 16-dim, label-free) ──────")
    for key, tag in RC_TAGS:
        if key not in rc:
            continue
        m = rc[key]
        w(f"\\newcommand{{\\RC{tag}Lin}}{{{f3(m['lin_auprc'])}}}")
        w(f"\\newcommand{{\\RC{tag}Gbdt}}{{{f3(m['gbdt_auprc'])}}}")
        w(f"\\newcommand{{\\RC{tag}Sil}}{{{f3(m['silhouette'])}}}")
        w(f"\\newcommand{{\\RC{tag}LEonepc}}{{{f3(m['label_efficiency']['0.01'])}}}")
        secs = m["train_seconds"]
        train = "$<1$" if (secs is not None and secs < 1) else (commanum(secs) if secs is not None else "--")
        w(f"\\newcommand{{\\RC{tag}Train}}{{{train}}}")
    g_t, s_t = rc["gater"]["train_seconds"], rc["scarf"]["train_seconds"]
    g_lin, p_lin = rc["gater"]["lin_auprc"], rc["pca16"]["lin_auprc"]
    w(f"\\newcommand{{\\RCgaterTimeFracScarf}}{{{round(100*g_t/s_t)}\\%}} % CARTA train time as % of SCARF's")
    w(f"\\newcommand{{\\RCscarfTimeExtra}}{{{round(100*(s_t-g_t)/g_t)}\\%}} % SCARF trains this % longer than CARTA")
    w(f"\\newcommand{{\\RCgaterPcaLinRatio}}{{{g_lin/p_lin:.1f}$\\times$}} % CARTA lin-probe vs PCA")

    # manual (figure/FTT) block
    L.append(MANUAL.rstrip("\n"))
    L.append("")

    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")
    print(f"  IEEE   gater16: lin={f3(base_row(bi, 'gater16')[0])} "
          f"gbdt={f3(base_row(bi, 'gater16')[1])} auc={f3(base_row(bi, 'gater16')[2])}")
    print(f"  TF     gater16: lin={f3(base_row(bt, 'gater16')[0])} "
          f"gbdt={f3(base_row(bt, 'gater16')[1])} auc={f3(base_row(bt, 'gater16')[2])}  lift={lift}x")
    print(f"  CatBoost IEEE-gbdt={f3(ig)}, TF gbdt={f3(tg)}")
    print(f"  RepComp, gater lin={f3(rc['gater']['lin_auprc'])}; scarf lin={f3(rc['scarf']['lin_auprc'])}; "
          f"pca lin={f3(rc['pca16']['lin_auprc'])}; gater {round(100*g_t/s_t)}% of SCARF train time")
    print("  NOTE: EP*/Cluster*/FTT* macros are from MANUAL block – refresh after C2 figure regen.")


if __name__ == "__main__":
    main()
